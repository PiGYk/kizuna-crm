"""Реальна адреса клієнта з-за nginx.

Навіщо: Django слухає за зворотним проксі, тому REMOTE_ADDR — це завжди
докер-шлюз (172.21.0.1), і в журналах axes ВСІ клієнти виглядали як одна
адреса. Розслідувати скарги «не можу зайти» було нічим.

Чому не django-ipware: axes вміє ним користуватись, але пакет у нас не
встановлений — і axes МОВЧКИ падає на REMOTE_ADDR. Ставити залежність
заради трьох рядків і перезбирати образ дорожче, ніж написати їх.

⚠️БЕЗПЕКА — чому БЕРЕМО ОСТАННЮ адресу, а не першу:
X-Forwarded-For — список «клієнт, проксі1, проксі2…», і клієнт може
надіслати свій заголовок із підробленою адресою. nginx із
`$proxy_add_x_forwarded_for` ДОПИСУЄ реальну адресу В КІНЕЦЬ. Тобто
останній елемент додали МИ, і лише йому можна вірити. Якби брали перший —
зловмисник підставляв би будь-що і обходив блокування перебору.
"""


def client_ip_from_proxy(request):
    xff = request.META.get("HTTP_X_FORWARDED_FOR", "")
    if xff:
        parts = [p.strip() for p in xff.split(",") if p.strip()]
        if parts:
            return parts[-1]          # ← дописав наш nginx, не клієнт
    return request.META.get("REMOTE_ADDR")
