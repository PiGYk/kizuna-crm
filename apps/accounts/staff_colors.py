"""Постійні кольори працівників у графіку роботи.

Наказ Олега 18.10: «унікальні статичні кольори кожному асистенту і лікарю,
щоб усі, навіть не читаючи прізвище, розуміли, хто».

Колір — властивість людини, а не ролі: зберігається в `User.shift_color`
ключем палітри (не hex), тож відтінки можна підправити тут, не чіпаючи базу.
Призначається сам при першому показі графіка і далі не змінюється — інакше
звільнення одного працівника перефарбовувало б усіх наступних.

Порядок палітри підібрано так, щоб ПЕРШІ кольори були максимально далекі
один від одного: у малій клініці 4–5 людей отримують синій, червоний,
зелений, фіолетовий, помаранчевий. Жовтого й бурштинового немає навмисно —
золото в CRM уже означає «сьогодні» і головні кнопки.
"""

# ключ, фон, текст, крапка (Tailwind 100 / 800 / 500 — контраст тексту ≥ 7:1)
PALETTE = [
    ('sky',     '#e0f2fe', '#075985', '#0ea5e9'),
    ('rose',    '#ffe4e6', '#9f1239', '#f43f5e'),
    ('emerald', '#d1fae5', '#065f46', '#10b981'),
    ('violet',  '#ede9fe', '#5b21b6', '#8b5cf6'),
    ('orange',  '#ffedd5', '#9a3412', '#f97316'),
    # 18.10 visual-inspector: teal шостим давав 13° від emerald — Софія й
    # Олег були одного зеленого. Шостий і сьомий заповнюють найбільші
    # дірки кола: lime між помаранчевим і зеленим, fuchsia між фіолетовим і
    # червоним. Близькі до вже виданих (teal, cyan, red, pink) — у кінець.
    ('lime',    '#ecfccb', '#3f6212', '#84cc16'),
    ('fuchsia', '#fae8ff', '#86198f', '#d946ef'),
    ('indigo',  '#e0e7ff', '#3730a3', '#6366f1'),
    ('red',     '#fee2e2', '#991b1b', '#ef4444'),
    ('cyan',    '#cffafe', '#155e75', '#06b6d4'),
    ('pink',    '#fce7f3', '#9d174d', '#ec4899'),
    ('teal',    '#ccfbf1', '#115e59', '#14b8a6'),
]
_BY_KEY = {k: {'key': k, 'bg': bg, 'fg': fg, 'dot': dot} for k, bg, fg, dot in PALETTE}
# Людина без кольору (звільнена, з іншої клініки) — нейтральний сірий.
FALLBACK = {'key': '', 'bg': '#f3f4f6', 'fg': '#374151', 'dot': '#9ca3af'}


def color_of(user):
    return _BY_KEY.get(getattr(user, 'shift_color', '') or '', FALLBACK)


def ensure_colors(org, people):
    """Видає вільний колір кожному з `people`, у кого його ще немає.

    `people` — у порядку важливості (хто частіше виходить — першим), щоб
    найактивніші отримали найбільш розрізнювані кольори. Зайняті кольори
    рахуються по ВСІЙ клініці, включно зі звільненими, — так колір людини
    не дістанеться новенькому, поки старий запис живий в історії графіка.
    """
    from .models import User

    if not people or all(getattr(u, 'shift_color', '') for u in people):
        return
    taken = set(
        User.objects.filter(organization=org).exclude(shift_color='')
        .values_list('shift_color', flat=True)
    )
    keys = [k for k, *_ in PALETTE]
    for u in people:
        if u.shift_color:
            continue
        free = next((k for k in keys if k not in taken), None)
        if free is None:
            # Людей більше, ніж кольорів — по колу. Для клініки на 12+ людей
            # краще дати змогу обирати колір вручну, але зараз таких немає.
            free = keys[len(taken) % len(keys)]
        u.shift_color = free
        User.objects.filter(pk=u.pk).update(shift_color=free)
        taken.add(free)
