# -*- coding: utf-8 -*-
"""Листи супроводу тріалу: привітання, підказка, нагадування, підсумок.

Тексти навмисно прості й без маркетингового шуму — лист має читатись як
написаний людиною. Підпис міняється в SIGNATURE.
"""
from django.utils import timezone

CRM_URL = 'https://crm.kizuna.com.ua'
SIGNATURE = 'Олег, Kizuna CRM\n' + CRM_URL

# Види листів і на якому дні тріалу їх слати.
WELCOME = 'welcome'
DAY3 = 'day3'
BEFORE5 = 'before5'
BEFORE1 = 'before1'
EXPIRED = 'expired'

KINDS = (
    (WELCOME, 'Привітання'),
    (DAY3, 'Третій день'),
    (BEFORE5, 'За 5 днів до кінця'),
    (BEFORE1, 'За день до кінця'),
    (EXPIRED, 'Після закінчення'),
)


def _hello(name):
    return f'Вітаю, {name}!' if name else 'Вітаю!'


def _q(name):
    """Назва в лапках, але без подвійних — «Кабінет «Барбоскіни»» виглядає неохайно."""
    name = (name or '').strip()
    return name if ('«' in name or '"' in name) else f'«{name}»'


def _date(dt):
    return timezone.localtime(dt).strftime('%d.%m.%Y') if dt else ''


def build(kind, *, name, clinic, trial_ends=None):
    """Повертає (тема, текст). Тільки plain text — лист має виглядати особистим."""
    hello = _hello(name)
    ends = _date(trial_ends)
    clinic = _q(clinic)

    if kind == WELCOME:
        subject = 'Kizuna CRM — з чого почати'
        body = (
            f'{hello}\n\n'
            f'Ви завели {clinic} в Kizuna CRM. Дякую, що спробували.\n\n'
            f'Щоб система почала бути корисною, вистачить трьох кроків:\n'
            f'1. Додайте лікарів — Налаштування, розділ Користувачі.\n'
            f'2. Заведіть кількох клієнтів з тваринами.\n'
            f'3. Поставте перший запис у розкладі.\n\n'
            f'Далі підтягнеться решта: картка тварини з історією, каса, склад ліків, '
            f'нагадування клієнтам у Телеграм.\n\n'
            f'Доступ відкритий повністю до {ends}. Нічого не обрізано — це вся система.\n\n'
            f'Якщо десь застрягнете, просто відповідайте на цей лист.\n\n'
            f'{SIGNATURE}'
        )
    elif kind == DAY3:
        subject = 'Допомогти з першими кроками?'
        body = (
            f'{hello}\n\n'
            f'Ви заводили {clinic} в Kizuna CRM. Якщо ще не встигли розібратись — '
            f'це звична річ, на старті незрозуміло, за що хапатись.\n\n'
            f'Найшвидший спосіб відчути систему: заведіть одного клієнта з твариною і '
            f'поставте йому запис на завтра. Хвилин пʼять, і стане видно, як працює решта.\n\n'
            f'Якщо у вас уже є база в Excel або в іншій програмі — напишіть, перенесемо. '
            f'Це безкоштовно і зазвичай займає день.\n\n'
            f'Що саме не виходить? Відповідайте прямо на цей лист.\n\n'
            f'{SIGNATURE}'
        )
    elif kind == BEFORE5:
        subject = f'Безкоштовний період {clinic} закінчується {ends}'
        body = (
            f'{hello}\n\n'
            f'Безкоштовний доступ для {clinic} діє ще пʼять днів, до {ends}.\n\n'
            f'Далі система закриється, але дані нікуди не подінуться — усе, що ви завели, '
            f'лишається. Продовжите — працюєте з того самого місця.\n\n'
            f'Тарифи: Старт 990 грн на місяць, Клініка 1990, Мережа 3990. Функціонал у всіх '
            f'однаковий, уся система цілком. Різниця в тому, наскільки щільно ми на звʼязку.\n\n'
            f'Продовжити: {CRM_URL} — Налаштування, розділ Підписка.\n\n'
            f'Якщо потрібні інші умови — напишіть у відповідь, домовимось.\n\n'
            f'{SIGNATURE}'
        )
    elif kind == BEFORE1:
        subject = 'Завтра доступ закриється'
        body = (
            f'{hello}\n\n'
            f'Нагадую: завтра, {ends}, безкоштовний період для {clinic} закінчується.\n\n'
            f'Дані залишаються на місці. Щоб не було паузи в роботі, продовжте зараз: '
            f'{CRM_URL} — Налаштування, розділ Підписка.\n\n'
            f'Якщо Kizuna не підійшла — напишіть одним рядком чому. Це справді допомагає.\n\n'
            f'{SIGNATURE}'
        )
    elif kind == EXPIRED:
        subject = 'Доступ закрито, дані збережені'
        body = (
            f'{hello}\n\n'
            f'Безкоштовний період для {clinic} завершився, доступ закрито. Усе, що ви '
            f'завели, збережене — вмикається назад одразу після оплати.\n\n'
            f'Продовжити: {CRM_URL} — Налаштування, розділ Підписка.\n\n'
            f'Якщо передумали, теж нормально. Напишіть, що не зайшло: ціна, функціонал, '
            f'не той момент. Відповім на будь-яке питання.\n\n'
            f'{SIGNATURE}'
        )
    else:
        raise ValueError(f'невідомий вид листа: {kind}')

    return subject, body
