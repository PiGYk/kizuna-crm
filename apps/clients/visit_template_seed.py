def seed_visit_templates(org, *, only_if_empty=True):
    """Створює стартовий набір шаблонів для клініки.

    only_if_empty=True — не чіпаємо клініку, яка вже завела свої шаблони.
    Повторний виклик не плодить дублів: назва в межах клініки унікальна за
    перевіркою нижче.
    """
    from .models import VisitTemplate

    existing = set(
        VisitTemplate._base_manager.filter(organization=org).values_list('name', flat=True)
    )
    if existing and only_if_empty:
        return 0

    created = 0
    for name, complaint, diagnosis, treatment, notes in TEMPLATES:
        if name in existing:
            continue
        VisitTemplate._base_manager.create(
            organization=org,
            name=name,
            complaint=_html(complaint),
            diagnosis=_html(diagnosis),
            treatment=_html(treatment),
            notes=_html(notes) if any(notes) else '',
            is_active=True,
        )
        created += 1
    return created
